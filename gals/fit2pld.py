#!/usr/bin/env python3
"""Turn a galfit.py result (uN_fit.txt) into a GALasm GAL16V8 source.

complex mode:    every fitted output becomes a tristate output (Pn.T + Pn.E), which puts GALasm in mode 2.
Both modes: every other output-cell pin (12-19: inputs, never-enabled outputs, unused) becomes Pn.T = GND with
Pn.E = GND, so it is never driven (AC1 = 1, OE term false) instead of GALasm's NOTUSED default.
registered mode: Pn.R for registers, Pn.T + Pn.E for combinational outputs; pin 1 = CLK, pin 11 = OE (/OE).
Pins used only as inputs keep their Pn name, unused pins are NC, 10 = GND, 20 = VCC.

usage: python3 fit2pld.py u3/u3_fit.txt --mode complex --name ADSCSIU3 -o u3/u3.pld
"""
import argparse, re

def parse_fit(path):
    eqs, cur = {}, None
    for l in open(path):
        if l.startswith('#') or not l.strip(): cur = None; continue
        m = re.match(r'^(/?)P(\d+)(\.[REJT])?\s*=\s*(.*)$', l.strip())
        if m:
            neg, pin, suf, rhs = m.group(1) == '/', int(m.group(2)), (m.group(3) or ''), m.group(4)
            cur = (pin, suf or '.F'); eqs[cur] = [neg, [rhs]]
        elif l.strip().startswith('+') and cur:
            eqs[cur][1].append(l.strip()[1:].strip())
    return eqs

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('fit'); ap.add_argument('--mode', choices=('complex', 'registered'), required=True)
    ap.add_argument('--name', required=True); ap.add_argument('-o', '--out', required=True)
    ap.add_argument('--desc', default='')
    ap.add_argument('--names', help='CSV pin,name (board signal names, <= 8 chars) to replace the Pn names')
    a = ap.parse_args()
    eqs = parse_fit(a.fit)
    rename = {}
    if a.names:
        import csv
        rename = {int(r['pin']): r['name'] for r in csv.DictReader(open(a.names))}
    used = set()
    for (pin, suf), (neg, terms) in eqs.items():
        for t in terms: used |= {int(x) for x in re.findall(r'P(\d+)', t)}
    outs = {}
    for (pin, suf), v in eqs.items():
        outs.setdefault(pin, {})[suf] = v
    lines_eq = []
    names = {10: 'GND', 20: 'VCC'}
    if a.mode == 'registered': names[1], names[11] = 'CLK', 'OE'
    for pin in sorted(outs):
        o = outs[pin]
        if '.E' in o and o['.E'][1] == ['GND'] and '.F' not in o and '.R' not in o:
            continue                                    # never enabled: leave as NC / input
        names[pin] = f'P{pin}'
        if '.R' in o:
            neg, terms = o['.R']
            lines_eq.append(f'{"/" if neg else ""}P{pin}.R = ' + '\n    + '.join(terms))
        else:
            neg, terms = o['.F']
            lines_eq.append(f'{"/" if neg else ""}P{pin}.T = ' + '\n    + '.join(terms))
            en = o.get('.E', [False, ['VCC']])[1]
            lines_eq.append(f'P{pin}.E = ' + ' + '.join(en))
        lines_eq.append('')
    # Output-cell pins (12-19) that the copy must never drive: inputs and never-enabled outputs. GALasm leaves an
    # OLMC it does not see in an equation as NOTUSED with AC1 = 0, which in registered mode is a registered output
    # driven whenever /OE is low, and in complex mode an undocumented configuration. Declaring it a tristate output
    # with a GND enable gives AC1 = 1 and an OE term that is always false; feedback still reads the pin.
    for p in range(12, 20):
        if p not in outs or ('.F' not in outs[p] and '.R' not in outs[p]):
            names[p] = f'P{p}'
            lines_eq += [f'P{p}.T = GND', f'P{p}.E = GND', '']
    for p in used: names.setdefault(p, f'P{p}')
    for p in range(1, 21): names.setdefault(p, 'NC')
    if a.mode == 'complex' and any(n == 'CLK' for n in names.values()): raise SystemExit('bad names')
    if rename:
        sub = lambda s: re.sub(r'(?<![A-Za-z0-9])P(\d+)(?![0-9])', lambda m: rename.get(int(m.group(1)), m.group(0)), s)
        lines_eq = [sub(l) for l in lines_eq]
        for p in range(1, 21):
            if names[p] not in ('GND', 'VCC') and p in rename: names[p] = rename[p]
    src = ['GAL16V8', a.name[:8], '',
           ' '.join(f'{names[p]:4s}' for p in range(1, 11)).rstrip(),
           ' '.join(f'{names[p]:4s}' for p in range(11, 21)).rstrip(), ''] + lines_eq + [
           'DESCRIPTION', '', a.desc or f'Generated by fit2pld.py from {a.fit} ({a.mode} mode).'] + (
           [] if rename else ['Pin names are raw pin numbers (Pn) until the board nets are mapped.'])
    open(a.out, 'w').write('\n'.join(src) + '\n')
    print(open(a.out).read())

if __name__ == '__main__':
    main()
